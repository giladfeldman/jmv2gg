#' Convert analysis code into editable figures
#'
#' Conversion parses input and never executes it. Unsupported analyses remain
#' in the input and are recorded in the returned diagnostics. The output
#' starts with one figure setup block (style, export settings, helpers), and
#' each converted analysis is followed by a commented figure block.
#' @param code UTF-8 R source as one character string.
#' @param engine Plot output: both engines, ggplot2, or bettergg.
#' @param style Named presentation options: `stats` (statistics on the
#'   figures, default `FALSE`), `palette` (`"nejm"`, `"okabe_ito"`, `"grey"`,
#'   `"viridis"`), `grayscale`, `verbose` (full plain-language comments),
#'   `headings` (R Markdown only), `styler`.
#' @param figures Named publication export options: `size` (`"double"` 7.2 in,
#'   `"single"` 3.5 in, or `"custom"` with `width`/`height`), `dpi`, `formats`
#'   (any of `"png"`, `"pdf"`, `"tiff"`), `background`, `optimize_png`.
#' @return An object of class `jmv2gg_result` containing text, analysis records,
#'   diagnostics, and an export manifest.
#' @export
convert_code <- function(code, engine = c("both", "ggplot2", "bettergg"),
                         style = list(), figures = list()) {
  assert_text(code)
  engine <- match.arg(engine)
  options <- conversion_options(style, figures)
  parsed <- inspect_code(code)
  if (!is.null(parsed$error)) return(new_result(code, list(), list(diag_record(
    "error", "invalid_r", parsed$error)), engine))
  records <- parsed$analyses
  diagnostics <- c(parsed$diagnostics, options$diagnostics)
  reserved <- reserved_name_clash(all.names(parsed$expressions))
  if (!is.null(reserved)) return(new_result(code, list(), c(diagnostics, list(reserved)), engine))
  records <- assign_analysis_names(records, all.names(parsed$expressions))
  insertions <- list()
  plots <- list()
  packages <- character()
  for (i in seq_along(records)) {
    record <- records[[i]]
    out <- tryCatch(generate_analysis(record, engine, options), error = identity)
    if (inherits(out, "error")) {
      records[[i]]$status <- "unsupported"
      diagnostics <- c(diagnostics, list(diag_record("warning", "unsupported_analysis",
        conditionMessage(out), record$id, record$line)))
    } else {
      records[[i]]$status <- "converted"
      records[[i]]$mapping <- out$mapping
      key <- as.character(record$end_line)
      insertions[[key]] <- paste(c(insertions[[key]], "", out$code), collapse = "\n")
      plots <- c(plots, out$plots)
      packages <- c(packages, out$packages)
      diagnostics <- c(diagnostics, out$diagnostics)
    }
  }
  setup <- if (length(plots)) figure_setup_code(options, packages) else character()
  if (length(setup)) {
    styled <- style_generated(c(list(setup = setup), insertions), options)
    diagnostics <- c(diagnostics, styled$diagnostics)
    setup <- styled$pieces$setup
    insertions <- styled$pieces[-1L]
  }
  original_lines <- strsplit(code, "\n", fixed = TRUE)[[1]]
  transformed <- character()
  for (i in seq_along(original_lines)) transformed <- c(transformed, original_lines[i], insertions[[as.character(i)]])
  header <- c("# Generated by jmv2gg. Conversion does not execute this code.",
    "# Keep a copy of your source analysis and review the notes on each figure.")
  if (length(setup)) setup <- c(setup, "")
  output <- paste(c(header, "", setup, transformed), collapse = "\n")
  new_result(output, records, diagnostics, engine, plots)
}

assert_text <- function(x) {
  if (!is.character(x) || length(x) != 1L || is.na(x))
    stop("Supply one non-missing character string.", call. = FALSE)
}

`%||%` <- function(x, y) if (is.null(x)) y else x
r_text <- function(x) paste(deparse(x, width.cutoff = 500L, backtick = TRUE), collapse = "\n")
r_string <- function(x) encodeString(x, quote = '"')
r_name <- function(x) vapply(x,encodeString,character(1),quote="`",USE.NAMES=FALSE)
# A name as readable code: bare when syntactic, backticked otherwise.
r_sym <- function(x) vapply(x, function(v) if (identical(make.names(v), v)) v else encodeString(v, quote = "`"),
  character(1), USE.NAMES = FALSE)
safe_id <- function(x) {
  x <- gsub("[^a-zA-Z0-9_-]", "-", x)
  if (!nzchar(x)) "analysis" else substr(x, 1, 80)
}

diag_record <- function(severity, code, message, analysis_id = NULL, line = NULL, chunk = NULL) {
  list(severity = severity, code = code, message = message,
       analysis_id = analysis_id, line = line, chunk = chunk)
}

reserved_name_clash <- function(symbols) {
  clash <- intersect(symbols, figure_setup_names)
  if (!length(clash)) return(NULL)
  diag_record("error", "reserved_name", paste0("The source uses ", paste(clash, collapse = ", "),
    ", which the figure setup defines. Rename it before conversion."))
}

new_result <- function(text, analyses, diagnostics, engine, plots = list()) {
  converted <- sum(vapply(analyses, function(a) identical(a$status, "converted"), logical(1)))
  errors <- any(vapply(diagnostics, function(d) d$severity == "error", logical(1)))
  if (!length(analyses) && !errors) diagnostics <- c(diagnostics, list(diag_record(
    "warning", "no_analyses", "No supported analyses found. The source is preserved.")))
  missing_engine <- any(vapply(diagnostics,function(d) identical(d$code,"bettergg_mapping_unavailable"),logical(1)))
  status <- if (!converted) "failed" else if (errors || converted < length(analyses) || missing_engine) "partial" else "complete"
  structure(list(status = status, text = text, analyses = analyses,
    diagnostics = diagnostics, manifest = list(converter = "jmv2gg",
      version = jmv2gg_version, engine = engine, detected = length(analyses),
      converted = converted, plots = plots)), class = "jmv2gg_result")
}

#' @export
print.jmv2gg_result <- function(x, ...) {
  cat("jmv2gg:", x$status, "—", x$manifest$converted, "of", x$manifest$detected,
      "analyses converted;", length(x$manifest$plots), "figures\n")
  invisible(x)
}

# Options of 0.1 that no longer change anything (figures now follow the
# BetterGG designs). They are accepted with a visible note, never silently.
retired_style_options <- c("show_violin", "show_jitter", "jitter_width", "jitter_height")

conversion_options <- function(style, figures) {
  merge <- function(defaults, input, what) {
    if (!is.list(input) || (length(input) && (is.null(names(input)) || any(!nzchar(names(input))))))
      stop(what, " options must be a named list.", call. = FALSE)
    unknown <- setdiff(names(input), names(defaults))
    if (length(unknown)) stop("Unknown ", what, " option: ", paste(unknown, collapse = ", "), call. = FALSE)
    utils::modifyList(defaults, input)
  }
  diagnostics <- list()
  retired <- intersect(names(style), retired_style_options)
  if (length(retired)) {
    diagnostics <- list(diag_record("info", "retired_option", paste0("Style option(s) ", paste(retired, collapse = ", "),
      " no longer change the figures in jmv2gg ", jmv2gg_version, "; the figures follow the BetterGG designs.")))
    style <- style[setdiff(names(style), retired)]
  }
  s <- merge(list(stats = FALSE, palette = "nejm", grayscale = FALSE, theme = "apa7", verbose = TRUE,
    headings = FALSE, styler = TRUE), style, "style")
  for (n in c("stats", "grayscale", "verbose", "headings", "styler"))
    if (!is.logical(s[[n]]) || length(s[[n]]) != 1L || is.na(s[[n]])) stop("Invalid style option: ", n)
  if (!identical(s$theme, "apa7")) stop("The supported theme is apa7.")
  if (!is.character(s$palette) || length(s$palette) != 1L || !s$palette %in% c("nejm", "okabe_ito", "grey", "viridis"))
    stop("palette must be one of nejm, okabe_ito, grey, viridis.")
  f <- merge(list(size = "custom", dpi = 600, width = 7.2, height = 5.4, formats = "png",
    background = "white", optimize_png = FALSE), figures, "figure")
  if (!is.character(f$size) || length(f$size) != 1L || !f$size %in% c("custom", "single", "double"))
    stop("Figure size must be custom, single or double.")
  if (f$size != "custom") {
    f$width <- if (f$size == "single") 3.5 else 7.2
    if (is.null(figures$height)) f$height <- f$width * 3 / 4
  }
  for (n in c("dpi", "width", "height")) if (!is.numeric(f[[n]]) || length(f[[n]]) != 1 ||
    !is.finite(f[[n]]) || f[[n]] <= 0) stop("Figure dimensions and dpi must be positive finite numbers.")
  if (f$width * f$height * f$dpi^2 > 60000000) stop("Figure exceeds 60 million pixels. Reduce dimensions or dpi.")
  formats <- unlist(f$formats, use.names = FALSE)
  if (!is.character(formats) || !length(formats) || anyNA(formats) || !all(formats %in% c("png", "pdf", "tiff")))
    stop("Figure formats must be any of png, pdf, tiff.")
  f$formats <- unique(formats)
  if (!is.character(f$background) || length(f$background) != 1 || is.na(f$background)) stop("Invalid background.")
  if (!is.logical(f$optimize_png) || length(f$optimize_png)!=1L || is.na(f$optimize_png)) stop("optimize_png must be TRUE or FALSE.")
  list(style = s, figures = f, diagnostics = diagnostics)
}

#' Inspect actual runtime capabilities
#' @return A list separating conversion from tested preview support.
#' @export
runtime_capabilities <- function() {
  wasm <- grepl("emscripten", R.version$platform)
  list(r = R.version.string, wasm = wasm, conversion = TRUE,
    ggplot2_installed = requireNamespace("ggplot2", quietly = TRUE),
    emmeans_installed = requireNamespace("emmeans", quietly = TRUE),
    bettergg_installed = requireNamespace("BetterGG", quietly = TRUE),
    preview_verified = FALSE,
    html_rendering = if (wasm) "browser preview (knitr + markdown in WebR); full rendering in native R" else
      "native R with rmarkdown and Pandoc")
}
