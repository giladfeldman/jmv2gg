test_that("lossless optimization preserves pixels, dimensions and publication dpi", {
  skip_if_not_installed("png");skip_if_not_installed("ragg")
  if(!nzchar(Sys.which("oxipng"))) skip("Native oxipng executable is unavailable")
  path<-tempfile(fileext=".png")
  ragg::agg_png(path,width=3,height=2,units="in",res=300)
  graphics::plot(1:10,1:10,col="darkgreen",pch=16);grDevices::dev.off()
  original<-png::readPNG(path,native=TRUE,info=TRUE)
  result<-optimize_png(path)
  optimized<-png::readPNG(path,native=TRUE,info=TRUE)
  expect_true(result$success)
  expect_true(result$pixels_verified)
  expect_lte(result$after,result$before)
  expect_identical(as.integer(original),as.integer(optimized))
  expect_identical(dim(original),dim(optimized))
  expect_equal(attr(original,"info")$dpi,attr(optimized,"info")$dpi)
})
